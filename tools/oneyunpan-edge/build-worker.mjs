// Generates worker.js from snippet.js.
//
// Cloudflare's Snippet editor only accepts a single file, and a Worker that
// imports another module breaks as soon as the imported file loses its
// `export default` (for example when pasted through the dashboard, which
// renames assets and may truncate them). Keeping one generated, self-contained
// worker.js avoids that class of failure entirely.
//
// Usage: node build-worker.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.join(here, "snippet.js"), "utf8");

const marker = "export default {";
const index = source.indexOf(marker);
if (index === -1) {
  throw new Error("snippet.js must contain exactly one `export default {` block");
}

// Turn the Snippet handler into a local const, then add a Worker entrypoint
// that injects TICKET_KEYS from the environment before delegating to it.
const body = source.slice(0, index) + "const __handler = {" + source.slice(index + marker.length);

const wrapper = `
// ---------------------------------------------------------------------------
// Worker entrypoint (generated by build-worker.mjs - do not edit by hand).
//
// Workers can read secrets, so the ticket keys do not have to live in source:
//
//   wrangler secret put TICKET_KEYS
//   {"":"<base64 32-byte key>","mysite":"<another key>"}
//
// The deployment also still works with the hardcoded TICKET_KEYS above.
export default {
  async fetch(request, env, ctx) {
    if (env && env.TICKET_KEYS) {
      try {
        globalThis.__CR_TICKET_KEYS = JSON.parse(env.TICKET_KEYS);
      } catch {
        return new Response(
          JSON.stringify({ status: false, message: "TICKET_KEYS is not valid JSON" }),
          { status: 500, headers: { "content-type": "application/json" } },
        );
      }
    }
    return __handler.fetch(request, env, ctx);
  },
};
`;

const output = body.replace(/\s*$/, "\n") + wrapper;
fs.writeFileSync(path.join(here, "worker.js"), output);
console.log(`worker.js written (${Buffer.byteLength(output)} bytes)`);
